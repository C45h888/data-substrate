#!/bin/bash
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOSQL
DO \$youth\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '$LARAVEL_APP_USER') THEN
    CREATE ROLE "$LARAVEL_APP_USER" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '$LARAVEL_APP_PASSWORD';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '$LARAVEL_MIGRATE_USER') THEN
    CREATE ROLE "$LARAVEL_MIGRATE_USER" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '$LARAVEL_MIGRATE_PASSWORD';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '$BACKUP_USER') THEN
    CREATE ROLE "$BACKUP_USER" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '$BACKUP_PASSWORD';
  END IF;
END \$youth\$;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE "$POSTGRES_DB" TO "$LARAVEL_APP_USER", "$LARAVEL_MIGRATE_USER", "$BACKUP_USER";
GRANT USAGE, CREATE ON SCHEMA public TO "$LARAVEL_MIGRATE_USER";
GRANT USAGE ON SCHEMA public TO "$LARAVEL_APP_USER", "$BACKUP_USER";
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO "$LARAVEL_APP_USER";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "$LARAVEL_APP_USER";
GRANT ALL ON ALL TABLES IN SCHEMA public TO "$LARAVEL_MIGRATE_USER";
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO "$LARAVEL_MIGRATE_USER", "$LARAVEL_APP_USER";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO "$LARAVEL_MIGRATE_USER";
ALTER DEFAULT PRIVILEGES FOR ROLE "$LARAVEL_MIGRATE_USER" IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "$LARAVEL_APP_USER";
ALTER DEFAULT PRIVILEGES FOR ROLE "$LARAVEL_MIGRATE_USER" IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO "$LARAVEL_APP_USER";
ALTER DEFAULT PRIVILEGES FOR ROLE "$LARAVEL_MIGRATE_USER" IN SCHEMA public GRANT SELECT ON TABLES TO "$BACKUP_USER";
ALTER DEFAULT PRIVILEGES FOR ROLE "$LARAVEL_MIGRATE_USER" IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO "$BACKUP_USER";
GRANT SELECT ON ALL TABLES IN SCHEMA public TO "$BACKUP_USER";
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO "$BACKUP_USER";
EOSQL
# Phase B+: Nhost platform admin role (guarded; runs on fresh volumes and is idempotent)
if [ -n "${HASURA_ADMIN_USER:-}" ]; then
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOSQL2
DO \$youth\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '$HASURA_ADMIN_USER') THEN
    CREATE ROLE "$HASURA_ADMIN_USER" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '$HASURA_ADMIN_PASSWORD';
  END IF;
END \$youth\$;
GRANT CONNECT ON DATABASE "$POSTGRES_DB" TO "$HASURA_ADMIN_USER";
GRANT CREATE ON DATABASE "$POSTGRES_DB" TO "$HASURA_ADMIN_USER";
GRANT USAGE, CREATE ON SCHEMA public TO "$HASURA_ADMIN_USER";
CREATE SCHEMA IF NOT EXISTS auth AUTHORIZATION "$HASURA_ADMIN_USER";
GRANT ALL ON ALL TABLES IN SCHEMA public TO "$HASURA_ADMIN_USER";
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO "$HASURA_ADMIN_USER";
ALTER DEFAULT PRIVILEGES FOR ROLE "$POSTGRES_USER", "$LARAVEL_MIGRATE_USER" IN SCHEMA public GRANT ALL ON TABLES TO "$HASURA_ADMIN_USER";
ALTER DEFAULT PRIVILEGES FOR ROLE "$POSTGRES_USER", "$LARAVEL_MIGRATE_USER" IN SCHEMA public GRANT ALL ON SEQUENCES TO "$HASURA_ADMIN_USER";
EOSQL2
fi
